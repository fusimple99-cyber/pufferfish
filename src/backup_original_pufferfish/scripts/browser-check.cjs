const { chromium } = require('/Users/fusimple/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const out = path.resolve(__dirname, '../verification');
(async () => {
  const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-first-run', '--no-default-browser-check'] });
  const context = await browser.newContext({ viewport: { width: 1400, height: 1050 }, deviceScaleFactor: 1 });
  const page = await context.newPage();
  const errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if(m.type()==='error') errors.push(m.text()); });
  page.on('request', r => requests.push(r.url()));
  await page.goto('http://127.0.0.1:8765');
  await page.waitForFunction(() => window.puffer?.ready, { timeout: 120000 });
  await page.waitForTimeout(1500);
  const initial = await page.evaluate(() => window.puffer.inspect());
  await page.screenshot({ path: path.join(out, 'desktop-initial.png') });
  const hit = initial.hitPoint;
  await page.mouse.move(hit.x, hit.y);
  await page.mouse.down();
  await page.waitForTimeout(2200);
  const enlarged = await page.evaluate(() => window.puffer.inspect());
  assert(Math.abs(enlarged.scale - 1.35) < .001, 'Long hold reaches 1.35');
  assert.deepEqual(enlarged.camera, initial.camera, 'Camera remains fixed');
  assert(enlarged.uniform, 'All axes have identical scale');
  assert(enlarged.inFrame, 'Maximum fish fits viewport');
  await page.screenshot({ path: path.join(out, 'desktop-enlarged.png') });
  await page.mouse.up();
  await page.waitForTimeout(450);
  const before = await page.evaluate(() => window.puffer.inspect().scale);
  console.log("INITIAL", JSON.stringify(initial));
  await page.mouse.down();
  const after = await page.evaluate(() => window.puffer.inspect().scale);
  console.log('REPRESS', before, after);
  assert(Math.abs(after - before) < .04, 'Repress continues at current size');
  await page.waitForTimeout(400);
  await page.mouse.up();
  await page.waitForTimeout(1400);
  assert(Math.abs(await page.evaluate(() => window.puffer.inspect().scale) - 1) < .001, 'Release restores 1.0');
  await page.mouse.down();
  await page.waitForTimeout(400);
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await page.waitForTimeout(1400);
  assert.equal(await page.evaluate(() => window.puffer.inspect().scale), 1, 'Blur releases hold');
  await page.mouse.up();
  await page.mouse.move(hit.x, hit.y);
  await page.mouse.down();
  await page.waitForTimeout(350);
  await page.mouse.move(-10, -10);
  await page.waitForTimeout(1300);
  assert.equal(await page.evaluate(() => window.puffer.inspect().scale), 1, 'Leaving canvas releases hold');
  await page.mouse.up();
  await page.mouse.click(15, 15, { delay: 500 });
  assert.equal(await page.evaluate(() => window.puffer.inspect().scale), 1, 'Background does not inflate');
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const mp = await mobile.newPage();
  mp.on('pageerror', e => errors.push(e.message));
  await mp.goto('http://127.0.0.1:8765');
  await mp.waitForFunction(() => window.puffer?.ready, { timeout: 120000 });
  const mobileInitial = await mp.evaluate(() => window.puffer.inspect());
  const cdp = await mobile.newCDPSession(mp);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: mobileInitial.hitPoint.x, y: mobileInitial.hitPoint.y }] });
  await mp.waitForTimeout(2200);
  const mobileLarge = await mp.evaluate(() => window.puffer.inspect());
  assert(Math.abs(mobileLarge.scale - 1.35) < .001, 'Touch hold reaches maximum');
  assert(mobileLarge.inFrame, 'Mobile maximum fits viewport');
  await mp.screenshot({ path: path.join(out, 'mobile-enlarged.png') });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
  await mp.waitForTimeout(1400);
  assert.equal(await mp.evaluate(() => window.puffer.inspect().scale), 1, 'Touch cancellation restores size');
  await mp.screenshot({ path: path.join(out, 'mobile-initial.png') });
  await mp.setViewportSize({width:844,height:390});
  await mp.waitForTimeout(350);
  await mp.waitForFunction(() => window.puffer?.ready, {timeout:120000});
  assert(await mp.evaluate(() => window.puffer.inspect().inFrame), 'Resized landscape fits');
  await mp.screenshot({path:path.join(out,'mobile-landscape.png')});
  assert.equal(errors.length, 0, errors.join('\n'));
  assert(requests.every(url => url.startsWith('http://127.0.0.1:8765/') || url.startsWith('data:') || url.startsWith('blob:http://127.0.0.1:8765/')), 'No external runtime requests');
  fs.writeFileSync(path.join(out, 'browser-results.json'), JSON.stringify({ passed: true, initial, enlarged, mobileInitial, mobileLarge, errors, requests, checks: ['mouse hold', 'release', 'repress continuity', 'fixed camera', 'uniform scale', 'background miss', 'blur release', 'mobile touch hold', 'touch cancel', 'maximum fits desktop/mobile', 'local requests only'] }, null, 2));
  await browser.close();
  console.log('Browser checks passed.');
})().catch(e => { console.error(e); process.exit(1); });
